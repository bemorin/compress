// Writes THIRD_PARTY_NOTICES.md (for readers of the repository) and public/third-party-notices.txt
// (served with the site, next to the WebAssembly it covers) from the license files of the installed
// packages, plus the libavif and libaom texts kept in scripts/licenses/. Runs before every build.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8").trim();
const version = (name) => JSON.parse(read(`node_modules/${name}/package.json`)).version;

const parts = [
  ["jSquash (@jsquash/webp, avif, jpeg, png, oxipng, resize)", `@jsquash/webp ${version("@jsquash/webp")}, @jsquash/avif ${version("@jsquash/avif")}, @jsquash/jpeg ${version("@jsquash/jpeg")}, @jsquash/png ${version("@jsquash/png")}, @jsquash/oxipng ${version("@jsquash/oxipng")}, @jsquash/resize ${version("@jsquash/resize")}`, "node_modules/@jsquash/webp/LICENSE"],
  ["libwebp (in @jsquash/webp)", "WebP encoder, compiled to WebAssembly", "node_modules/@jsquash/webp/codec/LICENSE.codec.md"],
  ["libavif (in @jsquash/avif)", "AVIF encoder, compiled to WebAssembly", "scripts/licenses/libavif.txt"],
  ["libaom (in @jsquash/avif)", "AV1 encoder used by libavif", "scripts/licenses/libaom.txt"],
  ["libaom patent license", "Alliance for Open Media Patent License 1.0", "scripts/licenses/libaom-patents.txt"],
  ["MozJPEG / libjpeg-turbo (in @jsquash/jpeg)", "JPEG encoder, compiled to WebAssembly", "node_modules/@jsquash/jpeg/codec/LICENSE.codec.md"],
  ["Oxipng (in @jsquash/oxipng)", "PNG optimiser, compiled to WebAssembly", "node_modules/@jsquash/oxipng/codec/LICENSE.codec.md"],
  ["resize (in @jsquash/resize)", "Lanczos resizing, compiled to WebAssembly", "node_modules/@jsquash/resize/lib/resize/LICENSE.codec.md"],
  ["hqx (in @jsquash/resize)", "Bundled with the resizer, not used by this app", "node_modules/@jsquash/resize/lib/hqx/LICENSE.codec.md"],
  ["magic-kernel (in @jsquash/resize)", "Bundled with the resizer, not used by this app", "node_modules/@jsquash/resize/lib/magic-kernel/LICENSE.codec.md"],
  ["wasm-feature-detect", version("wasm-feature-detect"), "node_modules/wasm-feature-detect/LICENSE"],
  ["JSZip (used under MIT)", version("jszip"), "node_modules/jszip/LICENSE.markdown"],
  ["Next.js", version("next"), "node_modules/next/license.md"],
  ["React", version("react"), "node_modules/react/LICENSE"],
  ["Motion (framer-motion)", version("framer-motion"), "node_modules/framer-motion/LICENSE.md"],
  ["Lucide", version("lucide-react"), "node_modules/lucide-react/LICENSE"],
];

const missing = parts.filter(([, , path]) => !existsSync(new URL(`../${path}`, import.meta.url)));
if (missing.length) {
  console.error(`License files not found: ${missing.map(([, , path]) => path).join(", ")}`);
  process.exit(1);
}

const intro =
  "Compress's own code is under the MIT License (LICENSE). It is built with and ships the open-source parts below. " +
  "Each keeps its own license, reproduced in full here. This file is generated by scripts/notices.mjs.";

const markdown = [`# Third-party notices`, "", intro, ""];
const text = ["THIRD-PARTY NOTICES", "", intro, ""];
for (const [name, detail, path] of parts) {
  const body = read(path);
  markdown.push(`## ${name}`, "", detail, "", "```text", body, "```", "");
  text.push("=".repeat(78), name, detail, "-".repeat(78), body, "");
}

writeFileSync(new URL("../THIRD_PARTY_NOTICES.md", import.meta.url), `${markdown.join("\n")}\n`);
writeFileSync(new URL("../public/third-party-notices.txt", import.meta.url), `${text.join("\n")}\n`);
console.log(`Third-party notices written (${parts.length} parts).`);
